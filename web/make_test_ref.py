"""Write web/test-ref.js: mpmath reference values of zeta for web/test.html.

usage:  python web/make_test_ref.py      (needs mpmath; takes a minute or two)
"""
import json
import os

import mpmath

# (sigma center, sigma half, t center, t half, method)  -- same cases as test_zeta_gpu.py
CASES = [
    (-4.0, 8.0, 20.0, 22.0, "em"),
    (0.5, 1.5, 120.0, 20.0, "em"),
    (-25.0, 5.0, 5.0, 5.0, "em"),
    (3.0, 2.0, -30.0, 10.0, "em"),
    (0.5, 1.5, 600.0, 5.0, "em"),
    (0.5, 1.5, 1000.0, 5.0, "rs"),
    (0.5, 1.0, 3000.0, 3.0, "em"),
    (0.5, 1.0, 3000.0, 3.0, "rs"),
    (0.5, 1.0, 1e4, 3.0, "auto"),
    (0.5, 3.0, 1e5, 2.0, "auto"),
    (0.5, 1.0, 1e6, 1.0, "auto"),
    (0.5, 1.0, -1e6, 1.0, "auto"),
    (0.5, 1.0, 1e8, 0.5, "auto"),
    (0.5, 0.5, 1e10, 0.5, "auto"),
]
N = 12
LINES = [(0.0, 60.0), (5000.0, 10.0), (1e6, 5.0)]
NL = 200

mpmath.mp.dps = 20
out = {"N": N, "cases": [], "lines": []}
for sc, sh, tc, th, method in CASES:
    vals = []
    for j in range(N):
        for i in range(N):
            s = mpmath.mpc(sc + ((i + 0.5) / N * 2 - 1) * sh, mpmath.mpf(tc) + ((j + 0.5) / N * 2 - 1) * th)
            z = mpmath.zeta(s)
            vals.append([float(mpmath.log(abs(z))), float(mpmath.arg(z))])
    out["cases"].append({"case": [sc, sh, tc, th, method], "ref": vals})
    print("case", sc, tc, method)
for t0, w in LINES:
    ts = [t0 + k / (NL - 1) * w for k in range(NL)]
    out["lines"].append({"t0": t0, "w": w, "n": NL, "Z": [float(mpmath.siegelz(t)) for t in ts]})
    print("line", t0)
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "test-ref.js")
with open(path, "w") as f:
    f.write("// generated by make_test_ref.py\nconst TEST_REF = " + json.dumps(out) + ";\n")
print("wrote", path)
